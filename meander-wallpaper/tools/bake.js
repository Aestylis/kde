// Bakes a mature river into contents/ui/sim.js (the BAKED array, in channel widths, y relative to the valley axis).
// Usage: node tools/bake.js [seed]
const fs = require('fs'), vm = require('vm'), path = require('path')
const file = path.join(__dirname, '../contents/ui/sim.js')
let src = fs.readFileSync(file, 'utf8').replace(/\n\/\/ BAKED-BEGIN[\s\S]*$/, '\n')
const ctx = { Math, Array }
vm.createContext(ctx); vm.runInContext(src, ctx)
const cw = 14, w = 700 * cw, h = 1440
ctx.msg = { cmd: 'init', w, h, cw, seed: +process.argv[2] || 7, warm: 16000, history: 0, every: 1, era: 1, dt: 3, fresh: true }
const r = vm.runInContext('handle(msg)', ctx)
const out = []
for (let i = 0; i < r.pts.length; i += 2) out.push(+(r.pts[i] / cw).toFixed(2), +((r.pts[i + 1] - h / 2) / cw).toFixed(2))
fs.writeFileSync(file, src.replace(/\n+$/, '\n') + '\n// BAKED-BEGIN (generated by tools/bake.js, do not edit)\nvar BAKED = [' + out.join(',') + ']\n')
console.log('baked', out.length / 2, 'points')
